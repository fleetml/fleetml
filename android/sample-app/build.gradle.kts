// Enrollment key for the sample app: `fleetml.enrollmentKey=...` in android/local.properties
// (gitignored) or `-PfleetmlEnrollmentKey=...` on the Gradle command line.
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
val enrollmentKey: String = (project.findProperty("fleetmlEnrollmentKey") as String?)
    ?: localProps.getProperty("fleetml.enrollmentKey")
    ?: ""

// The server's address for a debug build, prefilled on the config screen and
// allowed to take plain HTTP in the debug network security config:
// `-PfleetmlDebugHost=<LAN IP>` for a phone over Wi-Fi, `localhost` for one
// over USB (adb reverse). Unset, the screen shows the emulator's 10.0.2.2.
// In PowerShell quote it, `"-PfleetmlDebugHost=<LAN IP>"`: unquoted, an IP
// address is cut at its first dot.
val debugHost: String = ((project.findProperty("fleetmlDebugHost") as String?)
    ?: localProps.getProperty("fleetml.debugHost")
    ?: "").trim()
require(debugHost.matches(Regex("[A-Za-z0-9.:-]*"))) { "fleetmlDebugHost must be a host name or IP address, got \"$debugHost\"" }

/** Writes the debug build's network security config: plain HTTP to the emulator's host, localhost and fleetmlDebugHost. */
abstract class DebugNetworkConfig : DefaultTask() {
    @get:Input abstract val host: Property<String>
    @get:OutputDirectory abstract val resDir: DirectoryProperty

    @TaskAction
    fun write() {
        val hosts = (listOf("10.0.2.2", "localhost", "127.0.0.1") + host.get()).filter { it.isNotEmpty() }.distinct()
        val file = resDir.get().file("xml/network_security_config.xml").asFile
        file.parentFile.mkdirs()
        file.writeText(buildString {
            append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n")
            append("<!-- Generated by the sample app's build (fleetmlDebugHost); debug builds only. -->\n")
            append("<network-security-config>\n    <domain-config cleartextTrafficPermitted=\"true\">\n")
            hosts.forEach { append("        <domain includeSubdomains=\"false\">$it</domain>\n") }
            append("    </domain-config>\n</network-security-config>\n")
        })
    }
}

val debugNetworkConfig = tasks.register<DebugNetworkConfig>("fleetmlDebugNetworkConfig") {
    host.set(debugHost)
    resDir.set(layout.buildDirectory.dir("generated/fleetml/res"))
}

androidComponents {
    onVariants(selector().withBuildType("debug")) { variant ->
        variant.sources.res?.addGeneratedSourceDirectory(debugNetworkConfig, DebugNetworkConfig::resDir)
    }
}

